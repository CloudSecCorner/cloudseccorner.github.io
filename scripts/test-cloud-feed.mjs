import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { createRequire } from 'node:module';
import { build } from 'esbuild';
import React from 'react';
import { renderToStaticMarkup } from 'react-dom/server';
import { StaticRouter } from 'react-router-dom';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const read = file => fs.readFileSync(path.join(root, file), 'utf8');
const snapshot = JSON.parse(read('priv/data/cloud-security-feed.json'));
const sources = JSON.parse(read('priv/data/cloud-security-sources.json')).sources;
assert.equal(snapshot.version, 1);
assert.equal(snapshot.refresh_interval_hours, 24);
assert.equal(snapshot.sources.length, sources.length);
assert(snapshot.items.length > 0 && snapshot.items.length <= 300);
assert(Number.isFinite(Date.parse(snapshot.updated_at)));
for (const mirror of ['public/data', 'priv/static/data']) assert.equal(read(`${mirror}/cloud-security-feed.json`), read('priv/data/cloud-security-feed.json'));
for (const file of ['cloud-security.xml', 'cloud-security.opml']) assert.equal(read(`public/feeds/${file}`), read(`priv/static/feeds/${file}`));
const urls = new Set();
let previousDate = Infinity;
for (const item of snapshot.items) {
  const source = sources.find(source => source.id === item.source_id);
  assert(source && item.source_name === source.name);
  const url = new URL(item.url);
  assert.equal(url.protocol, 'https:');
  assert(source.allowed_hosts.includes(url.hostname));
  assert(!url.username && !url.password && !url.hash);
  assert(!urls.has(item.url)); urls.add(item.url);
  const published = Date.parse(item.published_at);
  assert(Number.isFinite(published) && published <= previousDate); previousDate = published;
  assert.equal(item.description, undefined);
  assert.equal(item.content, undefined);
}

const compiled = await build({ absWorkingDir: root, entryPoints: ['src/components/CloudSecurityFeed.jsx'], bundle: true, write: false, platform: 'node', format: 'cjs', external: ['react', 'react-router-dom'] });
const module = { exports: {} };
new Function('require', 'module', 'exports', compiled.outputFiles[0].text)(createRequire(import.meta.url), module, module.exports);
const { CloudFeedView, filterFeedItems } = module.exports;
const render = props => renderToStaticMarkup(React.createElement(StaticRouter, { location: '/blog' }, React.createElement(CloudFeedView, { snapshot, ...props })));
const normal = render({});
assert.match(normal, /Daily Cloud Security Feed/);
assert.match(normal, /Subscribe via RSS/);
assert.match(normal, /Download OPML/);
assert.match(normal, /Feed addresses and source status/);
assert.match(normal, /Search cloud security headlines/);
assert.match(normal, /rel="noopener noreferrer"/);
assert.equal((normal.match(/class="cloud-feed-item"/g) || []).length, Math.min(15, snapshot.items.length));
for (const source of sources) assert(normal.includes(source.feed_url));
const selected = snapshot.items[0];
const results = filterFeedItems(snapshot.items, { source: selected.source_id, topic: selected.topic });
assert(results.length > 0 && results.every(item => item.source_id === selected.source_id && item.topic === selected.topic));
assert.equal(filterFeedItems(snapshot.items, { query: '___no_cloud_headline_matches___' }).length, 0);
assert.match(render({ query: '___no_cloud_headline_matches___' }), /No headlines match/);
assert.equal((render({ compact: true }).match(/target="_blank"/g) || []).length, Math.min(3, snapshot.items.length));
assert.match(render({ snapshot: { ...snapshot, updated_at: '2020-01-01T00:00:00Z', sources: snapshot.sources.map(source => ({ ...source, status: 'cached' })) } }), /over 36 hours old/);
assert.match(render({ error: 'Could not refresh. Showing the last available published feed.' }), /last available published feed/);
assert.match(render({ snapshot: { ...snapshot, items: [] } }), /No recent cloud security headlines have been imported/);
const hostile = render({ snapshot: { ...snapshot, items: [{ ...selected, title: '<script>malicious</script>' }] } });
assert(!hostile.includes('<script>malicious</script>'));
assert(hostile.includes('&lt;script&gt;'));
const workflow = read('.github/workflows/pages.yml');
assert.match(workflow, /cron: '30 0 \* \* \*'/);
assert(workflow.indexOf('run: mix feeds.refresh') < workflow.indexOf('run: npm run check'));
assert.match(workflow, /if: github.event_name == 'schedule'/);
assert.match(workflow, /Save validated daily feed snapshot/);
assert(workflow.indexOf('run: npm run test:export') < workflow.indexOf('Save validated daily feed snapshot'));
console.log(`Validated ${snapshot.items.length} attributed cloud headlines, metadata mirrors, reader filters, paging, empty/stale/error states, subscriptions, and daily Elixir refresh wiring.`);
